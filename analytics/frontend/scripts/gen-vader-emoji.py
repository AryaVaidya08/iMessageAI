"""Regenerates src/engine/query/vaderEmoji.ts and vaderLexicon.ts from the Python vaderSentiment
package data files (MIT licensed).
Usage: python gen-vader-emoji.py <site-packages/vaderSentiment dir> <out dir (src/engine/query)>"""
import json
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])

emoji = {}
for line in (src / "emoji_utf8_lexicon.txt").read_text(encoding="utf8").rstrip("\n").split("\n"):
    e, desc = line.strip().split("\t")[:2]
    emoji[e] = desc

lex = {}
for line in (src / "vader_lexicon.txt").read_text(encoding="utf8").rstrip("\n").split("\n"):
    if not line:
        continue
    w, m = line.strip().split("\t")[:2]
    lex[w] = float(m)

hdr = "// Generated by scripts/gen-vader-emoji.py from the Python vaderSentiment package (MIT). Do not edit.\n"
dump = lambda d: json.dumps(d, ensure_ascii=False, separators=(",", ":"))
(out / "vaderEmoji.ts").write_text(hdr + "export const VADER_EMOJI: Record<string, string> = " + dump(emoji) + ";\n")
(out / "vaderLexicon.ts").write_text(hdr + "export const VADER_LEXICON: Record<string, number> = " + dump(lex) + ";\n")
